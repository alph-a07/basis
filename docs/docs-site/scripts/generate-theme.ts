import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { docsIntent } from '../src/config/docs-intent.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

// Locate docs-runtime build artifact
const possibleRuntimePaths = [
  path.resolve(__dirname, '../../docs-runtime/build/dist/js/productionLibrary/Basis-docs-runtime.js'),
  path.resolve(__dirname, '../../../docs/docs-runtime/build/dist/js/productionLibrary/Basis-docs-runtime.js'),
];

let runtimePath: string | null = null;
for (const p of possibleRuntimePaths) {
  if (fs.existsSync(p)) {
    runtimePath = p;
    break;
  }
}

if (!runtimePath) {
  console.error('❌ Could not locate Basis-docs-runtime.js artifact. Run ./gradlew :docs-runtime:compileKotlinJs first.');
  process.exit(1);
}

console.log('Resolving fixed docsIntent using Basis docs-runtime...');
const runtime = require(runtimePath);
const intentJson = JSON.stringify(docsIntent);

const responseJson = runtime.io.github.alph_a07.basis.docs.runtime.resolveWithPrefix(intentJson, 'd');
const response = JSON.parse(responseJson);

if (!response.ok) {
  console.error('❌ Theme resolution failed for docsIntent:');
  if (response.violations) {
    for (const v of response.violations) {
      console.error(`  - [${v.path}] ${v.message}`);
    }
  }
  process.exit(1);
}

// Ensure report contains no severe violations
if (response.report && response.report.entries) {
  const violations = response.report.entries.filter((entry: any) => entry.status === 'Violated' || entry.status === 'Error');
  if (violations.length > 0) {
    console.error(`❌ Resolver report reported ${violations.length} violations for docsIntent:`);
    for (const v of violations) {
      console.error(`  - [${v.target}] ${v.message}`);
    }
    process.exit(1);
  }
}

const css = response.tokens.css;
if (!css || typeof css !== 'string' || css.length === 0) {
  console.error('❌ Resolver did not return CSS tokens block.');
  process.exit(1);
}

const stylesDir = path.resolve(__dirname, '../src/styles');
if (!fs.existsSync(stylesDir)) {
  fs.mkdirSync(stylesDir, { recursive: true });
}

const themeCssPath = path.join(stylesDir, 'theme.css');
fs.writeFileSync(themeCssPath, `/* Generated by generate-theme.ts from docsIntent. Do not edit directly. */\n\n${css}\n`, 'utf-8');

console.log(`✅ Successfully generated theme.css (${Object.keys(response.tokens.dark).length} tokens) at src/styles/theme.css`);
